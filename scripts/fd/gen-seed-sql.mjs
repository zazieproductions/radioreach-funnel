/**
 * Generates migrations/0002_fd_content.sql from data/fd/*.json (built by
 * build-fd-content.mjs). Idempotent: pure UPSERTs into content tables only.
 * Never references progress/notes/campaign tables, so re-seeding course
 * content cannot erase learner state.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const DATA = path.join(ROOT, "data", "fd");
const OUT = path.join(ROOT, "migrations", "0002_fd_content.sql");

const readJson = (f) => JSON.parse(fs.readFileSync(path.join(DATA, f), "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const now = "strftime('%Y-%m-%dT%H:%M:%SZ','now')";

const outline = readJson("outline.json");
const bodies = readJson("lesson-bodies.json");
const stations = readJson("stations.json");
const tasks = readJson("task-templates.json");
const tools = readJson("tools.json");

const lines = [];
lines.push(`-- Frequency Dominion content seed — GENERATED by scripts/fd/gen-seed-sql.mjs.`);
lines.push(`-- Do not edit by hand. Upserts only; learner data untouched.`);

// modules
for (const [i, m] of outline.modules.entries()) {
  lines.push(
    `INSERT INTO modules (id, title, promise, position, published, updated_at) VALUES (${q(m.id)}, ${q(m.title)}, ${q(m.promise)}, ${i}, 1, ${now})`,
    `ON CONFLICT(id) DO UPDATE SET title=excluded.title, promise=excluded.promise, position=excluded.position, updated_at=${now};`
  );
}

// lessons — content upsert keeps created_at, bumps version for re-seeds
for (const m of outline.modules) {
  for (const [j, lesson] of m.lessons.entries()) {
    const b = bodies[lesson.id];
    if (!b) throw new Error(`missing body for ${lesson.id}`);
    const exercise = {
      kind: "field-exercise",
      prompt: "Complete every drill below with real, verifiable answers, then confirm the pass standard.",
      items: b.drills.map((d) => ({ id: `d${d.n}`, label: d.title, description: d.prompt, minutes: d.minutes, type: "response", passStandard: d.passStandard })),
      worksheets: b.worksheets.filter((w) => w.kind === "table"),
      confirmations: b.community.length ? [{ id: "community", text: "One community drill answered (optional but strengthens calibration)." , required: false }] : [],
    };
    const pass = {
      policy: "all-responses-min-words",
      minWords: 40,
      requireAllDrills: true,
      requireWorksheetCells: 0,
      note: b.drills.map((d) => d.passStandard).filter(Boolean).join(" · "),
    };
    lines.push(
      `INSERT INTO lessons (id, module_id, code, title, minutes, exercise_minutes, position, published, truth, masterclass_json, field_protocol_json, warnings_json, decoder_json, worksheets_json, community_json, exercise_json, pass_json, tool_links_json, print_asset, version, created_at, updated_at)
       VALUES (${q(lesson.id)}, ${q(m.id)}, ${q(lesson.code)}, ${q(lesson.title)}, ${lesson.minutes}, ${b.exerciseMinutes || 0}, ${j}, 1, ${q(lesson.truth)}, ${q(JSON.stringify(b.masterclass))}, ${q(JSON.stringify(b.warroom))}, ${q(JSON.stringify(b.warnings))}, ${q(JSON.stringify(b.decoderNotes))}, ${q(JSON.stringify(b.worksheets))}, ${q(JSON.stringify(b.community))}, ${q(JSON.stringify(exercise))}, ${q(JSON.stringify(pass))}, ${q(JSON.stringify(b.toolLinks || []))}, ${q("courses/frequency-dominion/frequency-dominion-course.zip")}, 1, ${now}, ${now})
       ON CONFLICT(id) DO UPDATE SET module_id=excluded.module_id, code=excluded.code, title=excluded.title, minutes=excluded.minutes, exercise_minutes=excluded.exercise_minutes, position=excluded.position, truth=excluded.truth, masterclass_json=excluded.masterclass_json, field_protocol_json=excluded.field_protocol_json, warnings_json=excluded.warnings_json, decoder_json=excluded.decoder_json, worksheets_json=excluded.worksheets_json, community_json=excluded.community_json, exercise_json=excluded.exercise_json, pass_json=excluded.pass_json, tool_links_json=excluded.tool_links_json, version=lessons.version+1, updated_at=${now};`,
    );
  }
}

// stations
lines.push(`BEGIN;`);
for (const st of stations) {
  lines.push(
    `INSERT INTO stations (id, callsign, dial, name, city, city_label, state, lat, lon, coord_basis, ring, format, specialty_program, gatekeeper_role, gatekeeper_name, contact_route, source_url, verified_at, data_risk, angle, import_batch, updated_at)
     VALUES (${st.id}, ${q(st.callsign)}, ${q(st.dial)}, ${q(`${st.callsign} ${st.dial}`.trim())}, ${q(st.city)}, ${q(st.cityLabel)}, ${q(st.state)}, ${st.lat}, ${st.lon}, ${q(st.coordBasis)}, ${q(st.ring)}, ${q(st.format)}, ${q(st.program)}, ${q(st.gatekeeperRole)}, ${q(st.gatekeeperName)}, ${q("")}, ${q("")}, '2026-08-31', 10, ${q(st.angle)}, 'master-package', ${now})
     ON CONFLICT(id) DO UPDATE SET callsign=excluded.callsign, dial=excluded.dial, name=excluded.name, city=excluded.city, city_label=excluded.city_label, state=excluded.state, lat=excluded.lat, lon=excluded.lon, coord_basis=excluded.coord_basis, ring=excluded.ring, format=excluded.format, specialty_program=excluded.specialty_program, gatekeeper_role=excluded.gatekeeper_role, gatekeeper_name=excluded.gatekeeper_name, angle=excluded.angle, updated_at=${now};`
  );
}
lines.push(`COMMIT;`);

// course assets
const assets = {
  "task-templates": tasks,
  decoder: tools.decoder,
  subjectLines: tools.subjectLines,
  pitchVault: tools.pitchVault,
  followUps: tools.followUps,
  audioVault: tools.audioVault,
  audit: tools.audit,
  epk: tools.epk,
  compliance: tools.compliance,
  playbooks: tools.playbooks,
  releaseCalendar: tools.releaseCalendar,
  relationship: tools.relationship,
  arsenal: tools.arsenal,
  courseOverview: tools.courseOverview,
  heatMapRules: tools.heatMapRules,
};
for (const [key, value] of Object.entries(assets)) {
  lines.push(
    `INSERT INTO course_assets (key, value_json, updated_at) VALUES (${q(key)}, ${q(JSON.stringify(value))}, ${now}) ON CONFLICT(key) DO UPDATE SET value_json=excluded.value_json, updated_at=${now};`
  );
}

fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(
  `wrote ${path.relative(ROOT, OUT)} — ${outline.modules.length} modules, ${Object.keys(bodies).length} lessons, ${stations.length} stations, ${Object.keys(assets).length} assets (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`
);
